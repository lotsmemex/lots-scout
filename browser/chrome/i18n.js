// UI language for the extension. Chinese source strings are the keys; English comes from EN.
// Pages read the choice synchronously from extension localStorage; it is mirrored to
// chrome.storage.local.uiLang so the service worker can title its menus. Outside a page (node tests,
// service worker) the pages' default is Chinese.
const KEY = "memex.lang";
const page = typeof document !== "undefined" && typeof localStorage !== "undefined";
export const langPref = () => (page && localStorage.getItem(KEY)) || "system";
export const resolveLang = (pref, browserLang) =>
  pref === "zh" || pref === "en" ? pref : /^zh\b/i.test(browserLang || "") ? "zh" : "en";
export const uiLang = page ? resolveLang(langPref(), navigator.language) : "zh";
export const LOCALE = uiLang === "en" ? "en-US" : "zh-CN";

export function tx(zh, ...args) {
  const text = uiLang === "en" ? (EN[zh] ?? zh) : zh;
  return args.length ? text.replace(/\{(\d+)\}/g, (_, i) => String(args[Number(i)])) : text;
}
export const txIn = (lang, zh) => (lang === "en" ? (EN[zh] ?? zh) : zh);

// Localizes the static text, placeholders and labels of an extension page.
export function localizeDocument(doc) {
  doc.documentElement.lang = uiLang === "en" ? "en" : "zh-CN";
  doc.title = tx(doc.title);
  const walker = doc.createTreeWalker(doc.body, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const key = node.data.trim();
    if (key && EN[key]) node.data = node.data.replace(key, tx(key));
  }
  for (const el of doc.querySelectorAll("[placeholder],[aria-label],[title]")) {
    for (const attr of ["placeholder", "aria-label", "title"]) {
      const value = el.getAttribute(attr);
      if (value && EN[value]) el.setAttribute(attr, tx(value));
    }
  }
}

export async function setLangPref(value) {
  if (value === "system") localStorage.removeItem(KEY); else localStorage.setItem(KEY, value);
  await chrome.storage.local.set({ uiLang: value });
  location.reload();
}

